export function getSktTooltipWords(chapterId: number): TooltipWord[] {
  return SKT_TOOLTIP_WORDS[chapterId] ?? []
}

// WordMap adapter for chapter reader tooltip rendering
export type WordMap = Record<string, { meaning: string }>

export function getSktWordMap(chapterId: number): WordMap {
  const words = getSktTooltipWords(chapterId)
  const map: WordMap = {}
  words.forEach(w => {
    map[w.word.toLowerCase()] = { meaning: w.meaning }
  })
  return map
}
